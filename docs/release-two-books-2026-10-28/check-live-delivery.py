"""Verify delivered release bytes and response policies. curl avoids Python urllib's rejected default UA. No credentials."""
import concurrent.futures, hashlib, json, pathlib, subprocess, sys, tempfile
origin, website, output, mode = sys.argv[1:]
root = pathlib.Path(website)
record = json.loads((root / "src/content/reader-books.json").read_text())
checks = []
def check(name, ok, detail=None):
    checks.append(dict(name=name, ok=bool(ok), **({"detail": detail} if not ok else {})))
with tempfile.TemporaryDirectory(prefix="delivery-", dir=pathlib.Path(__file__).parents[2] / "build") as scratch:
    jobs = []
    for book in record["books"]:
        base, bid = book["path"], book["book"]
        paths = ["index.html", "llms.txt", "sitemap.xml", f"agent/{bid}/index.md", f"agent/{bid}/full.md", f"agent/{bid}/manifest.json", f"covers/{bid}.jpg"]
        paths += [e["path"] for e in book["reader"]["edition"]["embeds"]]
        paths += [str(p.relative_to(root / "public" / base.lstrip("/"))) for p in (root / "public" / base.lstrip("/") / "assets").glob("index-*.js")]
        for p in paths:
            urlpath = base + (p[:-10] if p.endswith("index.html") else p)
            jobs.append((urlpath, root / "public" / base.lstrip("/") / p, "embed" if p.startswith("embeds/") else "reader"))
    jobs += [("/", root / "dist/index.html", "site"), ("/llms.txt", root / "dist/llms.txt", "site"), ("/sitemap.xml", root / "dist/sitemap.xml", "site"), ("/robots.txt", root / "dist/robots.txt", "site")]
    def fetch(item):
        i, (urlpath, file, kind) = item
        header, body = pathlib.Path(scratch) / f"{i}.headers", pathlib.Path(scratch) / f"{i}.body"
        result = subprocess.run(["curl", "--silent", "--show-error", "--location", "--max-time", "40", "--dump-header", str(header), "--output", str(body), "--write-out", "%{http_code}", origin.rstrip("/") + urlpath], capture_output=True, text=True)
        raw = header.read_text() if header.exists() else ""
        last = raw.strip().split("\n\n")[-1]
        headers = {}
        for line in last.splitlines()[1:]:
            if ":" in line:
                k,v = line.split(":", 1); headers[k.lower()] = v.strip()
        return urlpath, file, kind, result.returncode, result.stdout, headers, body.read_bytes() if body.exists() else b""
    deliveries = []
    for urlpath, file, kind, code, status, headers, body in concurrent.futures.ThreadPoolExecutor(max_workers=6).map(fetch, enumerate(jobs)):
        check(f"{urlpath}: HTTP 200 and exact generated bytes", code == 0 and status == "200" and body == file.read_bytes(), dict(status=status, got=hashlib.sha256(body).hexdigest(), expected=hashlib.sha256(file.read_bytes()).hexdigest()))
        csp = headers.get("content-security-policy", "")
        if mode == "production" and kind != "site" and file.suffix == ".html":
            check(f"{urlpath}: proxy does not inject into book HTML", "no-transform" in headers.get("cache-control", ""), headers.get("cache-control"))
        if kind == "embed":
            check(f"{urlpath}: isolated but frameable", csp.startswith("sandbox allow-scripts;") and "connect-src 'none'" in csp and "frame-ancestors 'self'" in csp and "frame-ancestors 'none'" not in csp and "x-frame-options" not in headers, headers)
        elif kind == "reader":
            check(f"{urlpath}: reader CSP", "script-src 'self'" in csp and "frame-ancestors 'none'" in csp and headers.get("x-frame-options") == "DENY", headers)
        else:
            check(f"{urlpath}: site has no book policy", not csp and "x-frame-options" not in headers, headers)
        check(f"{urlpath}: crawler policy", headers.get("x-robots-tag") == "noindex" if mode == "preview" else "noindex" not in headers.get("x-robots-tag", ""), headers.get("x-robots-tag"))
        deliveries.append(dict(path=urlpath, status=status, sha256=hashlib.sha256(body).hexdigest(), headers={k:v for k,v in headers.items() if k in ["cache-control", "content-type", "content-security-policy", "x-frame-options", "x-robots-tag"]}))
result = dict(origin=origin, mode=mode, passed=sum(c["ok"] for c in checks), total=len(checks), checks=checks, deliveries=deliveries)
pathlib.Path(output).write_text(json.dumps(result, indent=2) + "\n")
print(f"{result['passed']}/{result['total']} delivery checks passed")
for c in checks:
    if not c["ok"]: print(c)
sys.exit(0 if all(c["ok"] for c in checks) else 1)
