"""Browser acceptance for the canonical-folder repair: on a private preview, every download/index/manifest anchor is ORIGIN + reader prefix + the selected
generated folder, and fetching it returns the exact bytes of that generated file (never a 200 HTML fallback); the prompt names the generator's public links.
Every request is answered from fixtures (scratch/accept, built by build-canonical-fixture.mts); nothing leaves the browser. Usage: python accept-canonical-folder-browser.py <phase>"""
import json,re,sys,mimetypes
from pathlib import Path
from urllib.parse import urlsplit,unquote
from playwright.sync_api import sync_playwright
E=Path(__file__).resolve().parent;A=(E/'scratch'/'accept').resolve();phase=sys.argv[1] if len(sys.argv)>1 else 'run'
PREVIEW='http://127.0.0.1:18793';PUBLIC='https://public.example.org'
FALLBACK=b'<!doctype html><title>reader</title><div id="root"></div>'  # what a single-page static host returns for any missing path
expected=json.loads((A/'expected.json').read_text())
checks=[];served={};blocked=[];errors=[];console_errors=[]
def check(name,ok,detail=None):
 checks.append(dict(name=name,passed=bool(ok),detail=detail))
 if not ok:print('FAIL '+name+' '+json.dumps(detail)[:600],flush=True)
with sync_playwright() as p:
 shell=sorted((Path.home()/'Library/Caches/ms-playwright').glob('chromium_headless_shell-*/chrome-headless-shell-mac-arm64/chrome-headless-shell'))[-1]
 browser=p.chromium.launch(executable_path=str(shell),headless=True)
 try:
  context=browser.new_context(service_workers='block');page=context.new_page();page.set_default_timeout(6000)
  page.on('pageerror',lambda e:errors.append(str(e)));page.on('console',lambda m:console_errors.append(m.text) if m.type=='error' else None)
  def route(r):
   u=urlsplit(r.request.url);cors={'Access-Control-Allow-Origin':'*'}
   if f'{u.scheme}://{u.netloc}' not in (PREVIEW,PUBLIC):
    blocked.append(r.request.url);r.abort();return
   rel=unquote(u.path).lstrip('/')
   if rel=='' or rel.endswith('/'):rel+='index.html'
   dest=(A/rel).resolve()
   # The public host has the reader but not the agent files (not yet deployed), and both hosts answer a missing path with the reader page, status 200.
   if u.netloc==PREVIEW.split('//')[1] and dest.is_relative_to(A) and dest.is_file() and dest.name!='expected.json':
    served[r.request.url]=str(dest.relative_to(A))
    r.fulfill(status=200,content_type=mimetypes.guess_type(dest.name)[0] or 'text/markdown',body=dest.read_bytes(),headers=cors);return
   served[r.request.url]='fallback'
   r.fulfill(status=200,content_type='text/html',body=FALLBACK,headers=cors)
  context.route('**/*',route)
  def mount(access,chapter):
   page.evaluate('x=>mount(x.a,x.c)',{'a':access,'c':chapter});page.wait_for_timeout(60)
   hrefs=page.locator('.publication-agent-links a').evaluate_all('els=>els.map(e=>e.getAttribute("href"))')
   prompt=page.locator('.publication-agent-prompt p').inner_text()
   return hrefs,prompt,[u.rstrip('.') for u in re.findall(r'https?://[^\s)]+',prompt)]
  def fetched(hrefs):
   return page.evaluate('async hs=>Promise.all(hs.map(async h=>{const r=await fetch(h);return {href:r.url,status:r.status,type:r.headers.get("content-type"),body:await r.text()}}))',hrefs)
  def downloads_are(tag,hrefs,base,directory):
   want=f'{PREVIEW}/{base}{directory}/review-book/'
   files=[want+n for n in ('full.md','index.md','manifest.json')]
   ok=hrefs==files
   got=fetched(hrefs) if hrefs else []
   for g in got:
    rel=g['href'][len(PREVIEW)+1:]
    disk=(A/rel)
    exact=disk.is_file() and served.get(g['href'])==rel and g['status']==200 and 'html' not in (g['type'] or '') and g['body']==disk.read_text()
    ok=ok and exact
   manifest=next((g for g in got if g['href'].endswith('manifest.json')),None)
   try:ok=ok and json.loads(manifest['body'])['book']['id']=='review-book'
   except Exception:ok=False
   check(tag+' downloads: origin+prefix+selected folder, exact generated bytes',ok,{'hrefs':hrefs,'expected':files,'served':[served.get(g['href']) for g in got],'statuses':[(g['status'],g['type']) for g in got]})
  # Repaired case and the forms that already worked, at root, sub-path and a preview prefix different from the canonical one.
  for base,site in [('', PUBLIC+'/'),('sub/reader/',PUBLIC+'/sub/reader/'),('preview/',PUBLIC+'/sub/reader/'),('sub/reader/',PUBLIC+'/'),('',PUBLIC+'/sub/reader/')]:
   for query in ['','?book=review-book&section=second','index.html?book=review-book']:
    page.goto(f'{PREVIEW}/{base}{query}')
    for directory in ['agent','static/agent','a/b/agent']:
     forms={'canonical-url':site+directory+'/','canonical-url-no-slash':site+directory,'relative':directory+'/','dot-relative':'./'+directory,'absolute-path':f'/{base}{directory}/','preview-url':f'{PREVIEW}/{base}{directory}/'}
     for form,path in forms.items():
      for chapter in ([False,True] if form.startswith('canonical') or query=='' else [True]):
       tag=f'[{base or "/"} site={site} {query or "-"} {directory} {form} chapter={chapter}]'
       hrefs,prompt,urls=mount({'siteUrl':site,'path':path},chapter)
       downloads_are(tag,hrefs,base,directory)
       e=expected[f'{site} {directory}'];want=[e['chapter'],e['index']] if chapter else [e['index'],e['full']]
       check(tag+' prompt names the generator public links and no preview host',urls==want and '127.0.0.1' not in prompt,{'urls':urls,'want':want})
  # Out-of-contract folders fall back to the default folder under the current reader root; the prompt keeps the canonical default.
  page.goto(f'{PREVIEW}/sub/reader/?book=review-book');site=PUBLIC+'/sub/reader/'
  for path in ['https://cdn.example.net/static/agent/','//cdn.example.net/static/agent/','https://public.example.org.evil.example/sub/reader/static/agent/','https://u:p@public.example.org/sub/reader/static/agent/',
               'http://public.example.org/sub/reader/static/agent/','https://public.example.org:444/sub/reader/static/agent/','https://public.example.org/sub/reader-other/static/agent/','https://public.example.org/sub/static/agent/',
               site+'../agent/',site+'%2e%2e/agent/',site+'static/%2fagent/',site+'static/agent/?x',site+'static/agent/#x',site+'static\\agent/',site+'stat ic/agent/','javascript:alert(1)//'+site,'data:text/html,'+site]:
   hrefs,prompt,urls=mount({'siteUrl':site,'path':path},False)
   downloads_are('[hostile '+path+']',hrefs,'sub/reader/','agent')
   check('[hostile '+path+'] prompt keeps the canonical default folder',urls==[expected[f'{site} agent']['index'],expected[f'{site} agent']['full']],urls)
  # A private or malformed siteUrl is ignored quietly: attachment prompt, no address in it, local default downloads.
  for bad in ['http://127.0.0.1:8773/','http://[::ffff:127.0.0.1]/','http://100.85.55.122/','https://localhost./','https://box.tail123.ts.net./','https://u:p@public.example.org/','nonsense','https:public.example.org/']:
   for path in ([bad+'static/agent/'] if ':' in bad else [])+['https://public.example.org/static/agent/']:
    hrefs,prompt,urls=mount({'siteUrl':bad,'path':path},True)
    downloads_are(f'[bad site {bad} path {path}]',hrefs,'sub/reader/','agent')
    check(f'[bad site {bad} path {path}] attachment prompt with no address','I have attached' in prompt and not urls and not re.search(r'\d+\.\d+\.\d+\.\d+|::|localhost|ts\.net',prompt),prompt)
  check('no page exceptions, console errors or outside requests',not errors and not console_errors and not blocked,{'errors':errors,'console':console_errors,'blocked':blocked})
 finally:browser.close()
failed=[c for c in checks if not c['passed']]
(E/f'accept-canonical-results-{phase}.json').write_text(json.dumps({'checks':checks,'blocked':blocked,'pageErrors':errors,'consoleErrors':console_errors,'browser':str(shell)},indent=1)+'\n')
print(f'{len(checks)} checks; {len(failed)} failures');sys.exit(1 if failed else 0)
