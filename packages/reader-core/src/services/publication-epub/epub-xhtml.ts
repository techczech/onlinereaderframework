import { renderPublicationContent } from '../../publication-content/index.js';

export const XHTML_NS = 'http://www.w3.org/1999/xhtml';
export const EPUB_NS = 'http://www.idpf.org/2007/ops';
const XML_NS = 'http://www.w3.org/XML/1998/namespace';
export const SVG_NS = 'http://www.w3.org/2000/svg';
export const MATH_NS = 'http://www.w3.org/1998/Math/MathML';

/** DP's five-character XML escape, with XML 1.0 forbidden characters removed. */
export function escapeXml(value: string): string {
  return xmlText(value).replace(/[<>&'"]/g, character => ({
    '<': '&lt;', '>': '&gt;', '&': '&amp;', "'": '&apos;', '"': '&quot;',
  })[character]!);
}

function xmlText(value: string): string {
  return value.replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\uFFFE\uFFFF\uD800-\uDFFF]/gu, '');
}

export function requireBrowserXml(): void {
  if (typeof DOMParser === 'undefined' || typeof XMLSerializer === 'undefined') {
    throw new Error('Publication EPUB export requires browser DOMParser and XMLSerializer APIs. Importing the module during SSR is supported.');
  }
}

export function parseXml(source: string, label: string): Document {
  const document = new DOMParser().parseFromString(source, 'application/xml');
  if (document.getElementsByTagName('parsererror').length) throw new Error(`Invalid XML in ${label}`);
  return document;
}

export function serializeXml(document: Document): string {
  const source = '<?xml version="1.0" encoding="utf-8"?>\n<!DOCTYPE html>\n' + new XMLSerializer().serializeToString(document);
  parseXml(source, 'generated XHTML');
  return source;
}

export function createXhtml(title: string, language: string, stylesheet: string): Document {
  return parseXml(`<html xmlns="${XHTML_NS}" xmlns:epub="${EPUB_NS}" lang="${escapeXml(language)}" xml:lang="${escapeXml(language)}"><head><title>${escapeXml(title)}</title><link rel="stylesheet" type="text/css" href="${stylesheet}"/></head><body/></html>`, title);
}

/** Recreate sanitised HTML as namespace-aware XML; never insert it in the live DOM. */
export function appendPublicationContent(document: Document, content: string, format: 'markdown' | 'html'): void {
  const safeHtml = renderPublicationContent(content, format);
  const source = new DOMParser().parseFromString(safeHtml, 'text/html');
  const body = document.getElementsByTagNameNS(XHTML_NS, 'body')[0];
  const copy = (node: Node, parent: Node): void => {
    if (node.nodeType === 3) {
      parent.appendChild(document.createTextNode(xmlText(node.textContent ?? '')));
    } else if (node.nodeType === 1) {
      const original = node as Element;
      const namespace = original.namespaceURI ?? XHTML_NS;
      const element = document.createElementNS(namespace, original.localName);
      for (const attribute of Array.from(original.attributes)) {
        // Namespace declarations are generated by XMLSerializer, never copied
        // from a source's potentially conflicting xmlns attribute.
        if (attribute.name === 'xmlns' || attribute.prefix === 'xmlns') continue;
        if (attribute.prefix === 'xml') element.setAttributeNS(XML_NS, attribute.name, xmlText(attribute.value));
        else element.setAttribute(attribute.name, xmlText(attribute.value));
      }
      parent.appendChild(element);
      for (const child of Array.from(original.childNodes)) copy(child, element);
    }
  };
  for (const child of Array.from(source.body.childNodes)) copy(child, body);
  // The shared renderer deliberately keeps Markdown footnote attributes.
  for (const reference of Array.from(body.querySelectorAll('a[data-footnote-ref], .footnote-ref a'))) {
    reference.setAttributeNS(EPUB_NS, 'epub:type', 'noteref');
  }
  for (const note of Array.from(body.querySelectorAll('[data-footnotes] li[id], .footnotes li[id]'))) {
    note.setAttributeNS(EPUB_NS, 'epub:type', 'footnote');
  }
}

export function addTextElement(document: Document, parent: Element, tag: string, text: string): Element {
  const element = document.createElementNS(XHTML_NS, tag);
  element.textContent = xmlText(text);
  parent.appendChild(element);
  return element;
}
